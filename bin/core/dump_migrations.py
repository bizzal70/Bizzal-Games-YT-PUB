#!/usr/bin/env python3
"""
Dumps all Supabase config tables as SQL INSERT statements.
Writes output to db/migrations/0002_baseline_seed_data.sql
Run inside GitHub Actions where BIZZAL_DB_URL is available.
"""
import os, json
import psycopg
from pathlib import Path

OUT = Path("db/migrations/0002_baseline_seed_data.sql")
OUT.parent.mkdir(parents=True, exist_ok=True)

db_url = os.environ["BIZZAL_DB_URL"]

def q(v):
    """Quote a value for SQL."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        if not v:
            return "ARRAY[]::text[]"
        escaped = [s.replace("'", "''") for s in v]
        return "ARRAY[" + ",".join(f"'{e}'" for e in escaped) + "]"
    if isinstance(v, dict):
        return "'" + json.dumps(v).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"

lines = []
lines.append("-- Baseline seed data snapshot")
lines.append("-- Generated by dump_migrations.py on " + __import__('datetime').datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"))
lines.append("-- Apply AFTER 0001_baseline_schema.sql")
lines.append("-- To re-apply: psql $BIZZAL_DB_URL < db/migrations/0002_baseline_seed_data.sql")
lines.append("")

TABLES = [
    ("rpg_systems", ["id","display_name","chain_tag","path_suffix","is_active","ruleset",
                     "target_seconds","reading_level","no_homebrew_mechanics","default_length",
                     "spice_rate","persona_default","voiceover_default_voice_pack_id",
                     "voiceover_default_tts_voice_id","active_srd_path","srd_pdf_path",
                     "reference_sources","bg_image_prompt_prefix","bg_image_prompt_suffix",
                     "music_prompt_prefix","music_prompt_suffix","enable_ai","enable_ai_script",
                     "enable_tts","enable_bg_image","enable_bg_music","enable_pdf_flavor",
                     "tts_voice_variety_lookback_days"]),
    ("system_weekly_spine", ["system_id","day_of_week","category"]),
    ("system_categories", ["system_id","category","persona","tones","voices","angles"]),
    ("system_category_angle_weights", ["system_id","category","angle","weight"]),
    ("system_tones", ["system_id","tone","voice_pack_id","tts_voice_ids"]),
    ("system_voices", ["system_id","voice_name","tts_voice_ids","hooks","ctas"]),
    ("system_voice_category_lines", ["system_id","voice_name","category","hooks","ctas"]),
    ("system_personas", ["system_id","persona","one_liner"]),
]

with psycopg.connect(db_url) as conn:
    with conn.cursor() as cur:
        for table, cols in TABLES:
            lines.append(f"-- {table}")
            lines.append(f"DELETE FROM {table};")
            cur.execute(f"SELECT {','.join(cols)} FROM {table} ORDER BY 1,2")
            rows = cur.fetchall()
            for row in rows:
                vals = ",".join(q(v) for v in row)
                lines.append(f"INSERT INTO {table} ({','.join(cols)}) VALUES ({vals});")
            lines.append(f"-- {table}: {len(rows)} rows")
            lines.append("")

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Written {len(lines)} lines to {OUT}")
print(f"Tables dumped: {[t for t,_ in TABLES]}")
